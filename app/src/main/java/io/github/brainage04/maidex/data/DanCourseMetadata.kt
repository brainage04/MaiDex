    private val coursesByVersion: Map<String, List<DanCourse>> = linkedMapOf(
        "CiRCLE PLUS" to circlePlusCourses(),
        "CiRCLE" to circleCourses(),
        "PRiSM PLUS" to prismPlusCourses(),
        "PRiSM" to prismCourses(),
        "BUDDiES PLUS" to buddiesPlusCourses(),
        "BUDDiES" to buddiesCourses(),
        "FESTiVAL PLUS" to festivalPlusCourses(),
        "FESTiVAL" to festivalCourses(),
        "UNiVERSE PLUS" to universePlusCourses(),
        "UNiVERSE" to universeCourses(),
        "Splash PLUS" to splashPlusCourses(),
    )

    val versions: List<String> = coursesByVersion.keys.toList()

    val courses: List<DanCourse> = coursesForVersion(version)

    fun coursesForVersion(version: String): List<DanCourse> = coursesByVersion.getValue(version)

    fun sourceUrl(region: AccountRegion, version: String = this.version): String {
        require(version in coursesByVersion) { "Unknown Dan course version: $version" }
        val id = version.lowercase().replace(' ', '-') + "-dan"
        return "https://arcade-songs.zetaraku.dev/maimai/gallery/?id=" +
            id + if (region == AccountRegion.INTERNATIONAL) "-intl" else ""
    }

    fun chartKey(track: DanTrack): String = listOf(
        normalizeSearch(track.title),
        track.type,
        track.difficulty,
    ).joinToString("\u001f")

    fun chartLookup(charts: List<SongChart>): Map<String, SongChart> = charts.associateBy { chart ->
        chartKey(DanTrack(chart.title, chart.type, chart.difficulty))
    }

